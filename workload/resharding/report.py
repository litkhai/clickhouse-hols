#!/usr/bin/env python3
"""results/<version>.json -> RESULTS.md and images/d-reads-<version>.svg. Stdlib only.

  python3 report.py [results/26.8.36.3.json]
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def n(x):
    return "-" if x is None else f"{x:,}" if isinstance(x, int) else str(x)


def shards(d, zero=False):
    """zero=True: a shard missing from a GROUP BY _shard_num result had 0 rows."""
    return " / ".join(n(d.get(str(k), d.get(k, 0 if zero else None))) for k in (1, 2, 3))


def prober_row(label, s):
    return (f"| {label} | {s['reads']} | {s['read_errors']} | {s['read_p50_ms']} / {s['read_p95_ms']} / {s['read_max_ms']} | "
            f"{s['reads_doubled']} / {s['reads_missing']} | {s['writes']} | {s['write_errors']} | "
            f"{s['write_p50_ms']} / {s['write_p95_ms']} / {s['write_max_ms']} |")


PROBER_HEAD = ("| window | reads | read errors | read ms p50 / p95 / max | reads doubled / missing | writes | write errors | write ms p50 / p95 / max |\n"
               "|---|---|---|---|---|---|---|---|")


def check_cell(c):
    if c["ok"]:
        return "PASS"
    parts = [f"{m['partition']}: expected {m['expected']} got {m['got']}" for m in c["mismatched"]]
    pr = c.get("probe") or {}
    if pr.get("acked_rows") and pr["acked_present"] != pr["acked_rows"]:
        parts.append(f"probe {pr['acked_present']:,}/{pr['acked_rows']:,} acked rows present")
    if pr.get("dup_rows"):
        parts.append(f"probe dup {pr['dup_rows']}")
    return "FAIL — " + "; ".join(parts)


def svg_reads(r, path, title):
    """Reads that succeeded, from 2 s before the first move to the end; one label per moved partition."""
    marks = r.get("marks", [])
    starts = [(t, w.split()[0], w) for t, w in marks if "fetch start" in w or "move to staging" in w]
    t_min = (starts[0][0] - 2) if starts else 0
    reads = [x for x in r["prober"]["reads"] if x[1] and x[0] >= t_min]
    if not reads:
        return
    t_max = max(x[0] for x in reads)
    lo = min(min(x[3] for x in reads), 0)
    hi = max(max(x[3] for x in reads), 0)
    span = (hi - lo) or 1
    W, H, L, R, T, B = 900, 320, 80, 20, 48, 48
    px = lambda t: L + (W - L - R) * (t - t_min) / (t_max - t_min)
    py = lambda v: T + (H - T - B) * (hi - v) / span
    pts = " ".join(f"{px(x[0]):.1f},{py(x[3]):.1f}" for x in reads)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="sans-serif" font-size="12" fill="#222">',
           f'<rect width="{W}" height="{H}" fill="#fff"/>',
           f'<text x="{L}" y="18" font-size="13">{title}</text>',
           f'<line x1="{L}" y1="{py(0):.1f}" x2="{W - R}" y2="{py(0):.1f}" stroke="#999"/>',
           f'<text x="{L - 6}" y="{py(0) + 4:.1f}" text-anchor="end">0</text>',
           f'<text x="{L - 6}" y="{py(lo) + 4:.1f}" text-anchor="end">{lo:,}</text>',
           f'<text x="{L - 6}" y="{py(hi) + 4:.1f}" text-anchor="end">+{hi:,}</text>',
           f'<line x1="{L}" y1="{H - B}" x2="{W - R}" y2="{H - B}" stroke="#ccc"/>']
    t = int(t_min) + 1
    while t <= t_max:
        out.append(f'<line x1="{px(t):.1f}" y1="{H - B}" x2="{px(t):.1f}" y2="{H - B + 4}" stroke="#999"/>')
        out.append(f'<text x="{px(t):.1f}" y="{H - B + 16}" text-anchor="middle">{t}</text>')
        t += 1
    out.append(f'<text x="{(W + L) / 2:.0f}" y="{H - 8}" text-anchor="middle">seconds since the prober started; one read every {r.get("read_every_s", 0.2)} s</text>')
    for t0, part, w in starts:
        kind = "fetch first" if "fetch" in w else "move first"
        out.append(f'<text x="{px(t0):.1f}" y="{T - 6}" text-anchor="middle">{part} ({kind})</text>')
    out.append(f'<polyline fill="none" stroke="#1f6feb" stroke-width="1.5" points="{pts}"/>')
    out.append(f'<text x="{L + 4}" y="{H - B - 6}" fill="#555">base rows seen − expected (+ doubled, − missing)</text>')
    out.append("</svg>")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


def main():
    # full runs only: results/<version>.json (a single option writes results/<version>-<option>.json)
    files = sys.argv[1:] or sorted(f for f in glob.glob(os.path.join(HERE, "results", "*.json")) if "-" not in os.path.basename(f))
    for f in files:
        R = json.load(open(f))
        v = R["version"]
        a, b, d, fl, st = R["a"], R["b"], R["d"], R["fail"], R["selftest"]
        L = [f"# Results — {v}", "",
             f"Generated by `report.py` from `results/{v}.json` (run `python3 run.py all`, {R['date']}). Every number is from that run.", "",
             f"ClickHouse {v} (server and Keeper), {R['rows']:,} rows on 2 shards × 2 replicas, then shard 3 (2 replicas). "
             f"Docker VM: {R['docker']}; servers capped at 2 CPUs and 900 MiB (`ch-s1r1`, which runs the copies, 1,400 MiB), Keeper 512 MiB / 1 CPU.", "",
             "Other containers running on the same Docker VM when the run started (`docker stats --no-stream`):", ""]
        L += [f"- `{x}`" for x in R.get("other_containers", [])] or ["- none"]
        L += ["", "## Selftest: the per-partition check", "",
              "| injected | result |", "|---|---|",
              f"| none | {check_cell(st['identical'])} |",
              f"| one row inserted twice | {check_cell(st['doubled'])} |",
              f"| that row deleted (both copies) | {check_cell(st['missing'])} |",
              f"| one `amount` changed, same count | count equal {st['changed_value']['count_equal']}, row hash equal {st['changed_value']['hash_equal']} |", ""]
        L += ["## Rows per shard (shard 1 / 2 / 3)", "",
              "| option | before | after |", "|---|---|---|",
              f"| A. weights 1:1:2, then 3,000,000 new rows | {shards(a['before'])} | {shards(a['after'])} |",
              f"| B. `INSERT … SELECT` from `remote()` into a new 3-shard table | {shards(b['before'])} | {shards(b['after'])} |",
              f"| D. 4 partitions moved to shard 3 | {shards(d['before'])} | {shards(d['after'])} |", ""]
        L += ["## A. New shard + weights", "",
              f"- `clusters.xml` rewritten on the host, no `SYSTEM RELOAD CONFIG`: every server showed shard 3 after "
              f"{min(a['pickup_s'].values())}–{max(a['pickup_s'].values())} s ({', '.join(f'{k} {s}' for k, s in sorted(a['pickup_s'].items()))}).",
              f"- 3,000,000 new rows with weights 1:1:2 went {shards(a['new_rows_by_shard'], True)} (insert {a['new_rows_insert_s']} s).",
              f"- Point lookups `WHERE user_id = …` with `optimize_skip_unused_shards = 1` (and `force_…`), 200 users: before "
              f"{a['lookups_before']['users_differ']} differ; after {a['lookups_after']['users_differ']} differ, {a['lookups_after']['rows_missed']:,} rows not returned.",
              f"- Check of the original rows: {check_cell(a['check'])}; new rows: {'PASS' if a['new_rows_check']['ok'] else 'FAIL'}.", "",
              PROBER_HEAD, prober_row("10 s before", a["baseline"]), prober_row("config change", a["during"]), prober_row("whole run", a["prober_total"]), ""]
        L += ["## B. `INSERT … SELECT` from `remote()`", "",
              "| partition | rows | seconds | rows/s |", "|---|---|---|---|"]
        L += [f"| {c['partition']} | {c['rows']:,} | {c['seconds']} | {c['rows_per_s']:,} |" for c in b["copies"]]
        L += ["", f"- Bulk copy {b['bulk_seconds']} s for {sum(c['rows'] for c in b['copies']):,} rows.",
              f"- Check before the cut-over: {check_cell(b['check_before_cutover'])}.",
              f"- Cut-over: writes paused, hot partition {b['hot']['partition']} ({b['hot']['rows_base']:,} base rows + probe rows) copied in "
              f"{b['hot']['copy_seconds']} s, reads and writes switched; writes frozen {b['freeze_seconds']} s.",
              f"- Check after: {check_cell(b['check'])}.",
              f"- Point lookups with `optimize_skip_unused_shards = 1` on the new table: {b['lookups_after']['users_differ']}/{b['lookups_after']['users']} differ.",
              f"- Replicas: {', '.join(f'{k} {c:,}' for k, c in b['replicas'].items())}.", "",
              PROBER_HEAD, prober_row("10 s before", b["baseline"]), prober_row("bulk copy", b["during_bulk"]), prober_row("whole run", b["prober_total"]), "",
              "Fault injection on the result (event_id in 202607):", "",
              "| step | check |", "|---|---|",
              f"| row inserted again | {check_cell(b['faults']['doubled'])} |",
              f"| row deleted (both copies) | {check_cell(b['faults']['missing'])} |",
              f"| row copied once from the old table | {check_cell(b['faults']['repaired'])} |", ""]
        L += ["## D. Partition relocation", "",
              f"Shard 3 joined cluster `old` with weight {d['shard3_weight']} (reads go to it, hashed writes do not: probe rows by shard {shards(d['probe_by_shard'], True)}).", "",
              "| partition | from | variant | step times (s) | exposed (s) |", "|---|---|---|---|---|"]
        for m in d["moves"]:
            steps = ", ".join(f"{k[:-2]} {m[k]}" for k in ("move_s", "fetch_s", "attach_s", "drop_s") if k in m)
            L.append(f"| {m['partition']} | shard {m['from']} | {m['variant']} | {steps} | {m['exposed_s']} |")
        L += ["", f"Reads every {d.get('read_every_s', 0.2)} s through the Distributed table, runs of reads whose base count was off:", ""]
        L += [f"- {w['from_s']}–{w['to_s']} s: {w['kind']}, up to {w['rows']:,} rows" for w in d["windows"]] or ["- none"]
        L += ["", f"- Check: {check_cell(d['check'])}.",
              f"- Point lookups with `optimize_skip_unused_shards = 1`: before {d['lookups_before']['users_differ']}/200 differ, after "
              f"{d['lookups_after']['users_differ']}/200 differ, {d['lookups_after']['rows_missed']:,} rows not returned.",
              f"- Replicas: {', '.join(f'{k} {c:,}' for k, c in d['replicas'].items())}.", "",
              PROBER_HEAD, prober_row("10 s before", d["baseline"]), prober_row("whole run", d["prober_total"]), "",
              f"![reads during D](images/d-reads-{v}.svg)", ""]
        L += ["## Failure: source replica killed during a `remote()` copy", "",
              "`docker kill rs-ch-s2r2` once the copy had read 50% of the partition. The copy read replica 2 first (`'r2|r1'`, `load_balancing = in_order`) "
              "and wrote through the new Distributed table to replica 1. Copies and retries were throttled with `max_network_bandwidth = 2000000` "
              "(unthrottled, a partition took about 0.4 s); the recovery copy after `DROP PARTITION` was not.", ""]
        for x in fl["runs"]:
            cr = x["copy_result"]
            res = f"error: `{cr['error'].splitlines()[0][:220]}`" if "error" in cr else f"finished in {cr['seconds']} s (before the kill landed)"
            st = {k: v for k, v in x["settings"].items() if k not in ("max_network_bandwidth", "insert_deduplication_token")}
            L += [f"### partition {x['partition']} ({x['rows']:,} rows), `insert_deduplication_token` = {x['token'] or 'none'}, "
                  f"{', '.join(f'`{k} = {v}`' for k, v in st.items()) or 'default block size and receive_timeout'}", "",
                  f"- Killed at read_rows {n(x.get('killed_at_read_rows'))}, written_rows {n(x.get('killed_at_written_rows'))}; copy {res}.",
                  f"- Left in the new table: {x['left_behind']['count']:,} rows ({x['left_behind']['uniq']:,} distinct) of {x['left_behind']['expected']:,}; check {check_cell(x['check_after_failure'])}.",
                  f"- Retry without dropping, replica still down: " + (f"error `{x['retry_error'][:160]}`" if "retry_error" in x else f"{x['retry_seconds']} s") +
                  f"; check {check_cell(x['check_after_retry'])}.",
                  f"- Replica back after {x['s2r2_back_s']} s; `DROP PARTITION` + copy {x['recovery_copy_seconds']} s; check {check_cell(x['check_after_recovery'])}.", ""]
        L += [PROBER_HEAD, prober_row("10 s before", fl["baseline"]), prober_row("both failures", fl["prober_during"]), "",
              f"Probe writes to the old table during the failures: {fl['probe_rs']['acked_present']:,}/{fl['probe_rs']['acked_rows']:,} acknowledged rows present, "
              f"{fl['probe_rs']['dup_rows']} doubled; {fl['probe_rs']['failed_batches']} batches failed ({fl['probe_rs']['failed_rows_present']} of their rows present).", ""]
        sample = [x for x in fl["runs"] if "error" in x["copy_result"]]
        if sample:
            L += ["Error text of the first failed copy:", "", "```text", sample[0]["copy_result"]["error"], "```", ""]
        with open(os.path.join(HERE, "RESULTS.md"), "w") as fo:
            fo.write("\n".join(L))
        svg_reads(d, os.path.join(HERE, "images", f"d-reads-{v}.svg"), f"D. base rows seen through the Distributed table minus expected — ClickHouse {v}")
        print("wrote RESULTS.md and images/d-reads-%s.svg" % v)


if __name__ == "__main__":
    main()
