#!/usr/bin/env python3
"""Resharding a self-managed ClickHouse cluster from 2 to 3 shards, measured.

Stdlib only. Talks to the six servers of docker-compose.yml over HTTP (127.0.0.1:18201-18206)
and rewrites conf.d/clusters.xml to change the cluster topology at runtime.

  python3 run.py up                 # docker compose up, wait for the servers
  python3 run.py selftest           # prove the per-partition check fires on injected faults
  python3 run.py a|b|d|fail         # one option from a fresh 2-shard state
  python3 run.py all                # selftest, a, d, fail, b (b last: its end state is the 3-shard layout)
  python3 run.py resume b d         # run steps into the existing results/<version>.json and .log
  python3 run.py down               # docker compose down -v

Every option starts from the same state: database rs, ROWS rows (default 12,000,000) over
2026-05-01 .. 2026-11-07 on shards 1-2, sharding key cityHash64(user_id).
Results go to results/<version>.json and a transcript to results/<version>.log.
"""
import json
import os
import subprocess
import sys
import threading
import time
import urllib.error
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
NODES = {"ch-s1r1": 18201, "ch-s1r2": 18202, "ch-s2r1": 18203, "ch-s2r2": 18204, "ch-s3r1": 18205, "ch-s3r2": 18206}
SHARD_NODES = {1: ["ch-s1r1", "ch-s1r2"], 2: ["ch-s2r1", "ch-s2r2"], 3: ["ch-s3r1", "ch-s3r2"]}
ROWS = int(os.environ.get("ROWS", "12000000"))
T0 = "2026-05-01 00:00:00"
SPAN = 190 * 86400  # 2026-05-01 .. 2026-11-07 00:00
INITIATOR = "ch-s1r1"  # runs the copies and the prober queries
ROW_HASH = "cityHash64(event_id, user_id, ts, kind, amount, payload)"
LOG = None
RESULT = {}


# ---------------------------------------------------------------- plumbing
def log(*a):
    line = " ".join(str(x) for x in a)
    print(line, flush=True)
    if LOG:
        LOG.write(line + "\n")
        LOG.flush()


class CHError(Exception):
    pass


def ch(node, sql, timeout=600, **settings):
    # the query goes in the body: the URL has a length limit (the probe check's id list exceeded it)
    url = f"http://127.0.0.1:{NODES[node]}/?" + urllib.parse.urlencode({k: str(v) for k, v in settings.items()})
    req = urllib.request.Request(url, data=sql.encode(), method="POST")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.read().decode()
    except urllib.error.HTTPError as e:
        raise CHError(e.read().decode().strip()[:1500]) from None
    except (urllib.error.URLError, ConnectionError, TimeoutError, OSError) as e:
        raise CHError(f"connection: {e}") from None


def rows(node, sql, **s):
    out = ch(node, sql + " FORMAT TSV", **s).strip()
    return [l.split("\t") for l in out.splitlines()] if out else []


def scalar(node, sql, **s):
    return ch(node, sql + " FORMAT TSV", **s).strip()


def compose(*args):
    return subprocess.run(["docker", "compose", *args], cwd=HERE, check=True, capture_output=True, text=True)


def wait_up(nodes=NODES, timeout=120):
    end = time.time() + timeout
    for n in nodes:
        while True:
            try:
                ch(n, "SELECT count() FROM system.zookeeper WHERE path = '/'", timeout=3)  # server and its Keeper session
                break
            except CHError:
                if time.time() > end:
                    raise
                time.sleep(0.5)


def pct(xs, p):
    if not xs:
        return None
    xs = sorted(xs)
    return round(xs[min(len(xs) - 1, int(round(p / 100 * (len(xs) - 1))))] * 1000, 1)


# ---------------------------------------------------------------- topology
def write_clusters(old_shards):
    """old_shards: list of (shard_no, weight). The cluster new3 (shards 1-3) is always defined."""

    def shard(n, w=None):
        reps = "".join(f"<replica><host>{h}</host><port>9000</port></replica>" for h in SHARD_NODES[n])
        wt = f"<weight>{w}</weight>" if w is not None else ""
        return f"<shard>{wt}<internal_replication>true</internal_replication>{reps}</shard>"

    xml = (
        "<!-- generated by run.py; do not edit -->\n<clickhouse><remote_servers>\n"
        f"<old>{''.join(shard(n, w) for n, w in old_shards)}</old>\n"
        f"<new3>{''.join(shard(n) for n in (1, 2, 3))}</new3>\n"
        "</remote_servers></clickhouse>\n"
    )
    with open(os.path.join(HERE, "conf.d", "clusters.xml"), "w") as f:
        f.write(xml)


def cluster_state(node, name="old"):
    return [tuple(map(int, r)) for r in rows(node, f"SELECT shard_num, shard_weight FROM system.clusters WHERE cluster = '{name}' AND replica_num = 1 ORDER BY shard_num")]


def wait_cluster(old_shards, reload=True, timeout=120):
    """Wait until every node shows the expected `old` cluster; return {node: seconds}."""
    want = [(n, 1 if w is None else w) for n, w in old_shards]
    t0 = time.time()
    seen = {}
    if reload:
        for n in NODES:
            ch(n, "SYSTEM RELOAD CONFIG")
    while len(seen) < len(NODES):
        for n in NODES:
            if n not in seen:
                try:
                    if cluster_state(n) == want:
                        seen[n] = round(time.time() - t0, 2)
                except CHError:
                    pass
        if time.time() - t0 > timeout:
            raise RuntimeError(f"cluster not picked up: {seen}")
        time.sleep(0.2)
    return seen


# ---------------------------------------------------------------- schema and data
def ddl(sql):
    ch(INITIATOR, sql, distributed_ddl_task_timeout=180)


def create_db(db, cluster):
    ddl(f"CREATE DATABASE IF NOT EXISTS {db} ON CLUSTER new3")
    ddl(f"""CREATE TABLE IF NOT EXISTS {db}.events_local ON CLUSTER new3 (
            event_id UInt64, user_id UInt64, ts DateTime, kind LowCardinality(String), amount UInt32, payload String)
        ENGINE = ReplicatedMergeTree('/clickhouse/tables/{db}/events_local/{{shard}}', '{{replica}}')
        PARTITION BY toYYYYMM(ts) ORDER BY (user_id, ts, event_id)""")
    ddl(f"CREATE TABLE IF NOT EXISTS {db}.events ON CLUSTER new3 AS {db}.events_local "
        f"ENGINE = Distributed({cluster}, {db}, events_local, cityHash64(user_id))")


def gen_select(n, offset=0, kind_expr=None, t0=T0, span=SPAN, lo=0, cnt=None):
    """Row `number` of n rows; lo/cnt generate only numbers lo .. lo+cnt-1 of the same sequence."""
    kind = kind_expr or "['view','click','cart','buy'][cityHash64(number, 2) % 4 + 1]"
    return (f"SELECT number + {offset} AS event_id, cityHash64(number + {offset}, 1) % 200000 AS user_id, "
            f"toDateTime('{t0}') + toUInt32(intDiv(number * {span}, {n})) AS ts, {kind} AS kind, "
            f"toUInt32(cityHash64(number + {offset}, 3) % 100000) AS amount, "
            f"repeat(hex(cityHash64(number + {offset}, 4)), 3) AS payload FROM numbers({lo}, {n if cnt is None else cnt})")


def sync_replicas(db, nodes=NODES):
    for n in nodes:
        ch(n, f"SYSTEM SYNC REPLICA {db}.events_local", timeout=600)


def reset():
    log("\n## reset: drop rs, rs_new; cluster old = shards 1-2; load", f"{ROWS:,}", "rows")
    write_clusters([(1, None), (2, None)])
    wait_cluster([(1, None), (2, None)])
    for db in ("rs", "rs_new"):
        ddl(f"DROP DATABASE IF EXISTS {db} ON CLUSTER new3 SYNC")
    # memory crept up over repeated resets until a load hit the 900 MiB cap: give it back before loading again
    for n in NODES:
        for q in ("SYSTEM DROP MARK CACHE", "SYSTEM DROP PRIMARY INDEX CACHE", "SYSTEM JEMALLOC PURGE"):
            ch(n, q)
    create_db("rs", "old")
    t = time.time()
    # one INSERT per 1/14 of the rows: a single 12M-row INSERT through the Distributed table hit the 900 MiB container cap
    step = -(-ROWS // 14)
    for lo in range(0, ROWS, step):
        ch(INITIATOR, f"INSERT INTO rs.events {gen_select(ROWS, lo=lo, cnt=min(step, ROWS - lo))}",
           distributed_foreground_insert=1)
    sync_replicas("rs")
    log(f"   loaded in {time.time() - t:.1f} s")


def per_shard(db, local=True):
    """Rows per shard, read from each shard's first replica (local table, so shards outside the cluster count too)."""
    out = {}
    for s, nodes in SHARD_NODES.items():
        try:
            out[s] = int(scalar(nodes[0], f"SELECT count() FROM {db}.events_local"))
        except CHError:
            out[s] = None
    return out


def replica_parity(db):
    """Rows on each replica of every shard; replicas of one shard must agree."""
    return {n: int(scalar(n, f"SELECT count() FROM {db}.events_local")) for n in NODES}


# ---------------------------------------------------------------- the check
CHECK_SQL = ("SELECT toYYYYMM(ts) AS p, count(), uniqExact(event_id), sum({h}) FROM {src} "
             "WHERE kind NOT IN ('probe') GROUP BY p ORDER BY p")


def snapshot(src="rs.events", node=INITIATOR):
    return {r[0]: (int(r[1]), int(r[2]), r[3]) for r in rows(node, CHECK_SQL.format(h=ROW_HASH, src=src))}


def probe_check(db, prober, node=INITIATOR):
    """Every acknowledged probe batch present exactly once; failed batches reported as present/absent."""
    res = {"acked_rows": 0, "acked_present": 0, "dup_rows": 0, "failed_batches": 0, "failed_rows_present": 0}
    if prober is None:
        return res
    total, uniq = map(int, rows(node, f"SELECT count(), uniqExact(event_id) FROM {db}.events WHERE kind = 'probe'")[0])
    res["dup_rows"] = total - uniq
    acked = [b for b in prober.batches if b[2]]
    res["acked_rows"] = sum(b[1] for b in acked)
    if acked:
        cond = " OR ".join(f"(event_id >= {s} AND event_id < {s + c})" for s, c, _ in acked)
        res["acked_present"] = int(scalar(node, f"SELECT uniqExact(event_id) FROM {db}.events WHERE kind = 'probe' AND ({cond})"))
    failed = [b for b in prober.batches if not b[2]]
    res["failed_batches"] = len(failed)
    if failed:
        cond = " OR ".join(f"(event_id >= {s} AND event_id < {s + c})" for s, c, _ in failed)
        res["failed_rows_present"] = int(scalar(node, f"SELECT count() FROM {db}.events WHERE kind = 'probe' AND ({cond})"))
    return res


def check(expected, db, prober=None, label="", only=False):
    """only=True: compare just the partitions in `expected` (a per-partition re-copy).
    Replicas are synced first: the Distributed read may pick a replica that has not fetched the last insert yet."""
    for n in NODES:
        try:
            ch(n, f"SYSTEM SYNC REPLICA {db}.events_local", timeout=300)
        except CHError:
            pass  # a node that is down on purpose
    got = snapshot(f"{db}.events")
    if only:
        got = {p: v for p, v in got.items() if p in expected}
    bad = []
    for p in sorted(set(expected) | set(got)):
        e, g = expected.get(p), got.get(p)
        if e != g:
            bad.append({"partition": p, "expected": e and e[:2], "got": g and g[:2],
                        "hash_equal": bool(e and g and e[2] == g[2])})
    pr = probe_check(db, prober)
    probe_ok = pr["acked_present"] == pr["acked_rows"] and pr["dup_rows"] == 0
    ok = not bad and probe_ok
    log(f"   check {label or db}: {'PASS' if ok else 'FAIL'}"
        f" — partitions {len(got)}/{len(expected)}, mismatched {len(bad)}"
        + (f", probe acked {pr['acked_present']}/{pr['acked_rows']} dup {pr['dup_rows']}" if prober else ""))
    for b in bad:
        log(f"     {b['partition']}: expected (count, uniq) {b['expected']} got {b['got']}")
    return {"ok": ok, "mismatched": bad, "probe": pr}


# ---------------------------------------------------------------- prober
class Prober:
    """Background reader (count of base rows through the Distributed table, every 0.2 s) and writer
    (50 probe rows, every 0.25 s, distributed_foreground_insert=1). Both go to INITIATOR."""

    def __init__(self, db, base_total, read_every=0.2):
        self.read_every = read_every
        self.db = db
        self.base_total = base_total
        self.reads, self.writes, self.batches, self.marks = [], [], [], []
        self.paused = threading.Event()
        self.idle = threading.Event()
        self.stop_ = threading.Event()
        self.seq = 10 ** 12
        self.t0 = time.time()

    def mark(self, what):
        self.marks.append((round(time.time() - self.t0, 2), what))

    def _reader(self):
        while not self.stop_.is_set():
            t = time.time()
            db = self.db
            try:
                v = int(scalar(INITIATOR, f"SELECT count() FROM {db}.events WHERE kind NOT IN ('probe', 'new')", timeout=10))
                self.reads.append((t - self.t0, True, time.time() - t, v - self.base_total, db))
            except CHError as e:
                self.reads.append((t - self.t0, False, time.time() - t, str(e)[:160], db))
            time.sleep(max(0, self.read_every - (time.time() - t)))

    def _writer(self):
        while not self.stop_.is_set():
            if self.paused.is_set():
                self.idle.set()
                time.sleep(0.05)
                continue
            self.idle.clear()
            t = time.time()
            start, n = self.seq, 50
            self.seq += n
            sql = (f"INSERT INTO {self.db}.events SELECT {start} + number, cityHash64({start} + number) % 200000, now(), "
                   f"'probe', 0, '' FROM numbers({n})")
            try:
                ch(INITIATOR, sql, timeout=10, distributed_foreground_insert=1)
                self.batches.append((start, n, True))
                self.writes.append((t - self.t0, True, time.time() - t, None))
            except CHError as e:
                self.batches.append((start, n, False))
                self.writes.append((t - self.t0, False, time.time() - t, str(e)[:160]))
            time.sleep(max(0, 0.25 - (time.time() - t)))

    def start(self):
        self.threads = [threading.Thread(target=f, daemon=True) for f in (self._reader, self._writer)]
        for th in self.threads:
            th.start()
        return self

    def pause_writes(self):
        self.paused.set()
        self.idle.wait(15)

    def resume_writes(self):
        self.paused.clear()

    def stop(self):
        self.stop_.set()
        for th in self.threads:
            th.join(15)

    def summary(self, a=None, b=None):
        a = 0 if a is None else a
        b = 1e18 if b is None else b
        rd = [r for r in self.reads if a <= r[0] <= b]
        wr = [w for w in self.writes if a <= w[0] <= b]
        ok_r = [r for r in rd if r[1]]
        devs = [r[3] for r in ok_r if r[3] != 0]
        return {
            "reads": len(rd), "read_errors": len(rd) - len(ok_r),
            "read_p50_ms": pct([r[2] for r in ok_r], 50), "read_p95_ms": pct([r[2] for r in ok_r], 95),
            "read_max_ms": pct([r[2] for r in ok_r], 100),
            "reads_off_by": len(devs), "reads_doubled": len([d for d in devs if d > 0]), "reads_missing": len([d for d in devs if d < 0]),
            "max_extra_rows": max([d for d in devs if d > 0], default=0), "max_missing_rows": -min([d for d in devs if d < 0], default=0),
            "writes": len(wr), "write_errors": len([w for w in wr if not w[1]]),
            "write_p50_ms": pct([w[2] for w in wr if w[1]], 50), "write_p95_ms": pct([w[2] for w in wr if w[1]], 95),
            "write_max_ms": pct([w[2] for w in wr if w[1]], 100),
            "read_error_samples": sorted({r[3] for r in rd if not r[1]})[:3],
            "write_error_samples": sorted({w[3] for w in wr if not w[1]})[:3],
        }

    def windows(self):
        """Contiguous runs of reads whose base count was off, as (start, end, sign, max |dev|)."""
        out, cur = [], None
        for t, ok, _, v, _ in self.reads:
            if ok and v != 0:
                s = 1 if v > 0 else -1
                if cur and cur[2] == s:
                    cur[1], cur[3] = t, max(cur[3], abs(v))
                else:
                    if cur:
                        out.append(cur)
                    cur = [t, t, s, abs(v)]
            elif cur:
                out.append(cur)
                cur = None
        if cur:
            out.append(cur)
        return [{"from_s": round(x[0], 2), "to_s": round(x[1], 2), "kind": "doubled" if x[2] > 0 else "missing", "rows": x[3]} for x in out]

    def dump(self):
        return {"reads": [list(r) for r in self.reads], "writes": [list(w) for w in self.writes], "marks": self.marks}


def baseline(prober, seconds=10):
    a = time.time() - prober.t0
    time.sleep(seconds)
    return prober.summary(a, time.time() - prober.t0)


# ---------------------------------------------------------------- skip-unused-shards probe
def point_lookups(db, users=range(0, 200)):
    """For each user: count with optimize_skip_unused_shards=1 (force) vs 0. Returns users that differ and rows missed."""
    diff, missed = 0, 0
    for u in users:
        full = int(scalar(INITIATOR, f"SELECT count() FROM {db}.events WHERE user_id = {u}", optimize_skip_unused_shards=0))
        skip = int(scalar(INITIATOR, f"SELECT count() FROM {db}.events WHERE user_id = {u}",
                          optimize_skip_unused_shards=1, force_optimize_skip_unused_shards=1))
        if skip != full:
            diff += 1
            missed += full - skip
    n = len(list(users))
    log(f"   point lookups with optimize_skip_unused_shards=1: {diff}/{n} users differ, {missed:,} rows not returned")
    return {"users": n, "users_differ": diff, "rows_missed": missed}


# ---------------------------------------------------------------- options
def opt_a():
    log("\n# A. add shard 3, bias writes with <weight>")
    reset()
    exp = snapshot()
    base_total = sum(v[0] for v in exp.values())
    r = {"before": per_shard("rs"), "lookups_before": point_lookups("rs")}
    pr = Prober("rs", base_total).start()
    r["baseline"] = baseline(pr)
    # automatic pick-up of the edited file (no SYSTEM RELOAD CONFIG)
    pr.mark("clusters.xml rewritten")
    a = time.time() - pr.t0
    write_clusters([(1, 1), (2, 1), (3, 2)])
    r["pickup_s"] = wait_cluster([(1, 1), (2, 1), (3, 2)], reload=False, timeout=180)
    pr.mark("all nodes see shard 3")
    log(f"   config picked up without a reload command: {r['pickup_s']}")
    r["during"] = pr.summary(a, time.time() - pr.t0)
    # new writes after the change: 3,000,000 rows of kind 'new'
    n_new = 3_000_000
    new_sql = gen_select(n_new, offset=10 ** 9, kind_expr="'new'", t0="2026-11-07 00:00:00", span=3600)
    t = time.time()
    ch(INITIATOR, f"INSERT INTO rs.events {new_sql}", distributed_foreground_insert=1)
    sync_replicas("rs")
    r["new_rows_insert_s"] = round(time.time() - t, 2)
    r["new_rows_by_shard"] = {int(s): int(c) for s, c in rows(INITIATOR, "SELECT _shard_num, count() FROM rs.events WHERE kind = 'new' GROUP BY 1 ORDER BY 1")}
    log(f"   {n_new:,} new rows by shard (weights 1:1:2): {r['new_rows_by_shard']}")
    pr.stop()
    r["after"] = per_shard("rs")
    r["lookups_after"] = point_lookups("rs")
    # check: base rows unchanged; the 'new' rows exactly those generated
    exp_new = snapshot_of_generator(new_sql)
    got_new = rows(INITIATOR, f"SELECT count(), sum({ROW_HASH}) FROM rs.events WHERE kind = 'new'")[0]
    exp_all = dict(exp)
    r["check"] = check_with_extra(exp_all, "rs", pr, extra_kinds=("new",))
    r["new_rows_check"] = {"expected": exp_new, "got": got_new, "ok": exp_new == got_new}
    log(f"   new rows check: {'PASS' if exp_new == got_new else 'FAIL'} {got_new}")
    r["prober_total"] = pr.summary()
    r["replicas"] = replica_parity("rs")
    log("   rows per shard before", r["before"], "after", r["after"])
    RESULT["a"] = r


def snapshot_of_generator(sql):
    return rows(INITIATOR, f"SELECT count(), sum({ROW_HASH}) FROM ({sql})")[0]


def check_with_extra(expected, db, prober, extra_kinds=()):
    """Like check() but excludes extra row kinds that are verified separately."""
    global CHECK_SQL
    saved = CHECK_SQL
    kinds = ", ".join(f"'{k}'" for k in ("probe",) + tuple(extra_kinds))
    CHECK_SQL = saved.replace("NOT IN ('probe')", f"NOT IN ({kinds})")
    try:
        return check(expected, db, prober)
    finally:
        CHECK_SQL = saved


SRC = "ch-s1r1|ch-s1r2,ch-s2r1|ch-s2r2"


def copy_partition(p, src=SRC, **extra):
    t = time.time()
    ch(INITIATOR, f"INSERT INTO rs_new.events SELECT * FROM remote('{src}', rs, events_local) "
                  f"WHERE toYYYYMM(ts) = {p}", distributed_foreground_insert=1, load_balancing="in_order", **extra)
    return round(time.time() - t, 2)


def opt_b():
    log("\n# B. INSERT … SELECT from remote() into a new 3-shard layout, partition by partition")
    reset()
    create_db("rs_new", "new3")
    exp = snapshot()
    base_total = sum(v[0] for v in exp.values())
    r = {"before": per_shard("rs")}
    pr = Prober("rs", base_total).start()
    r["baseline"] = baseline(pr)
    parts = sorted(exp)
    hot = parts[-1]
    bulk = parts[:-1]
    r["copies"] = []
    a = time.time() - pr.t0
    pr.mark("bulk copy start")
    for p in bulk:
        s = copy_partition(p)
        r["copies"].append({"partition": p, "rows": exp[p][0], "seconds": s, "rows_per_s": int(exp[p][0] / s)})
        log(f"   copied {p}: {exp[p][0]:,} rows in {s} s")
    pr.mark("bulk copy end")
    r["bulk_seconds"] = round(sum(c["seconds"] for c in r["copies"]), 2)
    r["during_bulk"] = pr.summary(a, time.time() - pr.t0)
    # natural negative control: before the hot partition and the writes made during the copy are moved
    sync_replicas("rs_new")
    r["check_before_cutover"] = check({p: exp[p] for p in exp}, "rs_new", pr, label="rs_new before cut-over")
    # cut-over: freeze writes, copy the hot partition, switch reads and writes, resume
    pr.mark("freeze start")
    f0 = time.time()
    pr.pause_writes()
    s = copy_partition(hot)
    pr.db = "rs_new"
    pr.resume_writes()
    r["freeze_seconds"] = round(time.time() - f0, 2)
    pr.mark("freeze end; reads and writes on rs_new")
    r["hot"] = {"partition": hot, "rows_base": exp[hot][0], "copy_seconds": s}
    log(f"   cut-over: writes frozen {r['freeze_seconds']} s (hot partition {hot}, {exp[hot][0]:,} base rows + probe rows, copy {s} s)")
    time.sleep(10)
    pr.stop()
    sync_replicas("rs_new")
    r["after"] = per_shard("rs_new")
    r["replicas"] = replica_parity("rs_new")
    r["check"] = check(exp, "rs_new", pr)
    r["lookups_after"] = point_lookups("rs_new")
    r["prober_total"] = pr.summary()
    r["prober"] = pr.dump()
    r["marks"] = pr.marks
    log("   rows per shard before", r["before"], "after", r["after"])
    # fault injection on the result: one doubled row, then one missing row, then repaired
    r["faults"] = inject_faults(exp, pr)
    RESULT["b"] = r


def inject_faults(exp, pr):
    out = {}
    victim = int(scalar(INITIATOR, "SELECT min(event_id) FROM rs_new.events WHERE kind != 'probe' AND toYYYYMM(ts) = 202607"))
    log(f"\n## fault injection on rs_new (event_id {victim}, partition 202607)")
    ch(INITIATOR, f"INSERT INTO rs_new.events SELECT * FROM rs_new.events WHERE event_id = {victim}", distributed_foreground_insert=1)
    out["doubled"] = check(exp, "rs_new", pr, label="after doubling one row")
    ch(INITIATOR, f"ALTER TABLE rs_new.events_local ON CLUSTER new3 DELETE WHERE event_id = {victim}",
       mutations_sync=2, distributed_ddl_task_timeout=180)
    out["missing"] = check(exp, "rs_new", pr, label="after deleting it (both copies)")
    # the doubled row went in as a 1-row block that the shard's deduplication log remembers; an identical block would be dropped
    ch(INITIATOR, f"INSERT INTO rs_new.events SELECT * FROM remote('ch-s1r1,ch-s2r1', rs, events_local) WHERE event_id = {victim}",
       distributed_foreground_insert=1, deduplicate_insert="disable")
    out["repaired"] = check(exp, "rs_new", pr, label="after re-copying it once")
    return out


def opt_d():
    log("\n# D. relocate whole partitions: FETCH PARTITION + ATTACH + DROP (and MOVE PARTITION TO TABLE as a staging step)")
    reset()
    exp = snapshot()
    base_total = sum(v[0] for v in exp.values())
    r = {"before": per_shard("rs")}
    # shard 3 joins the cluster for reads; weight 0 keeps hashed writes off it (if the server accepts 0)
    try:
        write_clusters([(1, 1), (2, 1), (3, 0)])
        wait_cluster([(1, 1), (2, 1), (3, 0)], timeout=30)
        r["shard3_weight"] = 0
    except Exception as e:  # noqa: BLE001 — record and fall back
        log(f"   weight 0 not accepted: {str(e)[:200]}")
        write_clusters([(1, 1), (2, 1), (3, 1)])
        wait_cluster([(1, 1), (2, 1), (3, 1)])
        r["shard3_weight"] = 1
    log(f"   shard 3 in cluster old with weight {r['shard3_weight']}")
    r["lookups_before"] = point_lookups("rs")
    ddl("CREATE TABLE rs.events_stage ON CLUSTER new3 AS rs.events_local "
        "ENGINE = ReplicatedMergeTree('/clickhouse/tables/rs/events_stage/{shard}', '{replica}') PARTITION BY toYYYYMM(ts) ORDER BY (user_id, ts, event_id)")
    pr = Prober("rs", base_total, read_every=0.02).start()  # 20 ms: the exposure windows are shorter than 0.2 s
    r["read_every_s"] = 0.02
    r["baseline"] = baseline(pr)
    r["moves"] = []
    # D1 fetch first: shard 1 -> shard 3 (expect a doubled window between ATTACH and DROP)
    for p in ("202605", "202606"):
        m = {"partition": p, "from": 1, "variant": "fetch-first"}
        pr.mark(f"{p} fetch start")
        t = time.time()
        ch("ch-s3r1", f"ALTER TABLE rs.events_local FETCH PARTITION {p} FROM '/clickhouse/tables/rs/events_local/01'")
        m["fetch_s"] = round(time.time() - t, 2)
        t = time.time()
        ch("ch-s3r1", f"ALTER TABLE rs.events_local ATTACH PARTITION {p}")
        m["attach_s"] = round(time.time() - t, 2)
        pr.mark(f"{p} attached on shard 3")
        t2 = time.time()
        ch("ch-s1r1", f"ALTER TABLE rs.events_local DROP PARTITION {p}", alter_sync=2)
        m["drop_s"] = round(time.time() - t2, 2)
        m["exposed_s"] = round(time.time() - t, 2)
        pr.mark(f"{p} dropped on shard 1")
        r["moves"].append(m)
        log(f"   {p} s1->s3 fetch-first: fetch {m['fetch_s']} s, attach {m['attach_s']} s, drop {m['drop_s']} s")
        time.sleep(2)
    # D2 move first: shard 2 -> staging -> shard 3 (expect a missing window between MOVE and ATTACH)
    for p in ("202607", "202608"):
        m = {"partition": p, "from": 2, "variant": "move-first"}
        pr.mark(f"{p} move to staging")
        t = time.time()
        ch("ch-s2r1", f"ALTER TABLE rs.events_local MOVE PARTITION {p} TO TABLE rs.events_stage", alter_sync=2)
        m["move_s"] = round(time.time() - t, 2)
        t1 = time.time()
        ch("ch-s3r1", f"ALTER TABLE rs.events_local FETCH PARTITION {p} FROM '/clickhouse/tables/rs/events_stage/02'")
        m["fetch_s"] = round(time.time() - t1, 2)
        t1 = time.time()
        ch("ch-s3r1", f"ALTER TABLE rs.events_local ATTACH PARTITION {p}")
        m["attach_s"] = round(time.time() - t1, 2)
        m["exposed_s"] = round(time.time() - t, 2)
        pr.mark(f"{p} attached on shard 3")
        ch("ch-s2r1", f"ALTER TABLE rs.events_stage DROP PARTITION {p}", alter_sync=2)
        r["moves"].append(m)
        log(f"   {p} s2->s3 move-first: move {m['move_s']} s, fetch {m['fetch_s']} s, attach {m['attach_s']} s")
        time.sleep(2)
    time.sleep(3)
    pr.stop()
    sync_replicas("rs")
    r["windows"] = pr.windows()
    for w in r["windows"]:
        log(f"   prober saw {w['kind']} rows {w['from_s']}–{w['to_s']} s (up to {w['rows']:,})")
    r["after"] = per_shard("rs")
    r["probe_by_shard"] = {int(s): int(c) for s, c in rows(INITIATOR, "SELECT _shard_num, count() FROM rs.events WHERE kind = 'probe' GROUP BY 1 ORDER BY 1")}
    log(f"   probe rows by shard (shard 3 weight {r['shard3_weight']}): {r['probe_by_shard']}")
    r["replicas"] = replica_parity("rs")
    r["check"] = check(exp, "rs", pr)
    r["lookups_after"] = point_lookups("rs")
    r["prober_total"] = pr.summary()
    r["prober"] = pr.dump()
    r["marks"] = pr.marks
    log("   rows per shard before", r["before"], "after", r["after"])
    RESULT["d"] = r


FAIL_SRC = "ch-s1r2|ch-s1r1,ch-s2r2|ch-s2r1"
FAIL_BW = 2_000_000  # bytes/s per query


def opt_fail():
    log("\n# failure: kill the source replica that a remote() copy is reading from (ch-s2r2)")
    reset()
    create_db("rs_new", "new3")
    exp = snapshot()
    base_total = sum(v[0] for v in exp.values())
    pr = Prober("rs", base_total).start()
    out = {"baseline": baseline(pr, 5), "runs": []}
    a = time.time() - pr.t0
    parts = sorted(exp)
    # The copy is throttled (max_network_bandwidth) so that the kill lands mid-copy: unthrottled, a partition took ~0.4 s.
    # Destination shards squash an INSERT into blocks of min_insert_block_size_rows (default 1,048,449) before writing a part,
    # so variants 2 and 3 lower it to show what a partly written partition does on retry.
    # Variant 1 keeps the default receive_timeout (300 s); 2 and 3 lower it to 30 s so that the run does not wait 5 minutes each.
    small = {"min_insert_block_size_rows": 100000, "max_insert_block_size": 100000, "receive_timeout": 30}
    for p, token, blocks in ((parts[0], None, {}), (parts[1], None, small), (parts[2], f"reshard-{parts[2]}", small)):
        out["runs"].append(fail_once(exp, pr, p, token, blocks))
    pr.stop()
    out["prober_during"] = pr.summary(a, time.time() - pr.t0)
    out["marks"] = pr.marks
    out["prober"] = pr.dump()
    # writes acknowledged while ch-s2r2 was down must be in rs
    sync_replicas("rs")
    out["probe_rs"] = probe_check("rs", pr)
    log(f"   prober while copies ran and the replica was down: {out['prober_during']}")
    log(f"   probe rows written to rs during the failures: acked {out['probe_rs']['acked_present']}/{out['probe_rs']['acked_rows']}, dup {out['probe_rs']['dup_rows']}")
    RESULT["fail"] = out


def fail_once(exp, pr, p, token, blocks):
    extra = dict(blocks, max_network_bandwidth=FAIL_BW)
    if token:
        extra["insert_deduplication_token"] = token
    log(f"\n## partition {p}, {exp[p][0]:,} rows, insert_deduplication_token = {token!r}, blocks {blocks or 'default'}")
    r = {"partition": p, "rows": exp[p][0], "token": token, "settings": extra}
    err = {}

    def run():
        try:
            err["seconds"] = copy_partition(p, src=FAIL_SRC, **extra)
        except CHError as e:
            err["error"] = str(e)

    th = threading.Thread(target=run)
    th.start()
    # wait until the copy has read part of the partition, then kill ch-s2r2. The copy reads replica 2 of each shard first
    # (in_order over 'r2|r1'); the Distributed insert writes to replica 1 (in_order), so the killed node is a source only.
    while th.is_alive():
        try:
            rd = rows(INITIATOR, "SELECT read_rows, written_rows FROM system.processes WHERE query LIKE 'INSERT INTO rs_new.events%' AND query NOT LIKE '%system.processes%'")
        except CHError:
            rd = []
        if rd and int(rd[0][0]) > exp[p][0] * 0.5:
            r["killed_at_read_rows"], r["killed_at_written_rows"] = int(rd[0][0]), int(rd[0][1])
            break
        time.sleep(0.05)
    pr.mark(f"{p}: kill rs-ch-s2r2")
    subprocess.run(["docker", "kill", "rs-ch-s2r2"], check=True, capture_output=True)
    th.join()
    r["copy_result"] = err
    log(f"   killed rs-ch-s2r2 at read_rows {r.get('killed_at_read_rows')}; copy -> {err}")
    up = [n for n in NODES if n != "ch-s2r2"]
    sync_replicas("rs_new", up)
    got = rows(INITIATOR, f"SELECT count(), uniqExact(event_id) FROM rs_new.events WHERE toYYYYMM(ts) = {p}")[0]
    r["left_behind"] = {"count": int(got[0]), "uniq": int(got[1]), "expected": exp[p][0]}
    log(f"   left in rs_new partition {p}: {int(got[0]):,} of {exp[p][0]:,} rows")
    subset = {p: exp[p]}
    r["check_after_failure"] = check(subset, "rs_new", None, only=True, label="partition after the failed copy")
    # retry while the replica is still down: remote() fails over to ch-s2r1 at connection time
    try:
        r["retry_seconds"] = copy_partition(p, src=FAIL_SRC, **extra)
    except CHError as e:
        r["retry_error"] = str(e)
    sync_replicas("rs_new", up)
    r["check_after_retry"] = check(subset, "rs_new", None, only=True, label=f"after retrying ({'same token' if token else 'no token'}) without dropping")
    # recovery: bring the replica back, drop the partition on the new layout and copy it again
    pr.mark(f"{p}: start rs-ch-s2r2")
    subprocess.run(["docker", "start", "rs-ch-s2r2"], check=True, capture_output=True)
    t = time.time()
    wait_up(["ch-s2r2"])
    r["s2r2_back_s"] = round(time.time() - t, 2)
    ch(INITIATOR, f"ALTER TABLE rs_new.events_local ON CLUSTER new3 DROP PARTITION {p}", distributed_ddl_task_timeout=180)
    r["recovery_copy_seconds"] = copy_partition(p, src=FAIL_SRC)  # unthrottled, default blocks, no token
    sync_replicas("rs_new")
    r["recovery_seconds"] = round(time.time() - t, 2)
    r["check_after_recovery"] = check(subset, "rs_new", None, only=True, label="after DROP PARTITION + copy")
    return r


def selftest():
    """The check must fire: compare a table with itself, then with one row doubled, one row missing."""
    log("\n# selftest: does the per-partition check fire?")
    reset()
    exp = snapshot()
    out = {"identical": check(exp, "rs", label="untouched")}
    v = int(scalar(INITIATOR, "SELECT min(event_id) FROM rs.events WHERE toYYYYMM(ts) = 202606"))
    ch(INITIATOR, f"INSERT INTO rs.events SELECT * FROM rs.events WHERE event_id = {v}", distributed_foreground_insert=1)
    out["doubled"] = check(exp, "rs", label="one row doubled")
    ch(INITIATOR, f"ALTER TABLE rs.events_local ON CLUSTER new3 DELETE WHERE event_id = {v}", mutations_sync=2, distributed_ddl_task_timeout=180)
    out["missing"] = check(exp, "rs", label="that row deleted")
    # changed value, same count: only the hash sees it
    w = int(scalar(INITIATOR, "SELECT min(event_id) FROM rs.events WHERE toYYYYMM(ts) = 202608"))
    ch(INITIATOR, f"ALTER TABLE rs.events_local ON CLUSTER new3 UPDATE amount = amount + 1 WHERE event_id = {w}", mutations_sync=2, distributed_ddl_task_timeout=180)
    got = snapshot()
    out["changed_value"] = {"partition": "202608", "count_equal": got["202608"][:2] == exp["202608"][:2],
                            "hash_equal": got["202608"][2] == exp["202608"][2]}
    log(f"   one value changed in 202608: count equal {out['changed_value']['count_equal']}, hash equal {out['changed_value']['hash_equal']}")
    RESULT["selftest"] = out


def main():
    global LOG
    cmd = sys.argv[1] if len(sys.argv) > 1 else "all"
    if cmd == "up":
        write_clusters([(1, None), (2, None)])
        compose("up", "-d")
        wait_up()
        print("up:", scalar(INITIATOR, "SELECT version()"))
        return
    if cmd == "down":
        compose("down", "-v")
        return
    resume = cmd == "resume"  # python3 run.py resume b: run steps into the existing results/<version>.json and .log
    if resume:
        cmd = "all"
    wait_up()
    version = scalar(INITIATOR, "SELECT version()")
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    tag = f"{version}-{cmd}" if cmd != "all" else version
    LOG = open(os.path.join(HERE, "results", f"{tag}.log"), "a" if resume else "w")
    if resume:
        RESULT.update(json.load(open(os.path.join(HERE, "results", f"{tag}.json"))))
        RESULT.setdefault("resumed", []).append({"at": time.strftime("%Y-%m-%d %H:%M:%S %Z"), "steps": sys.argv[2:]})
    log(f"{'resumed: ' if resume else ''}ClickHouse {version}; ROWS={ROWS:,}; {time.strftime('%Y-%m-%d %H:%M:%S %Z')}")
    RESULT.update({"version": version, "rows": ROWS, "date": time.strftime("%Y-%m-%d"),
                   "docker": subprocess.run(["docker", "info", "--format", "{{.NCPU}} CPU, {{.MemTotal}} B"], capture_output=True, text=True).stdout.strip()})
    others = subprocess.run(["docker", "stats", "--no-stream", "--format", "{{.Name}} {{.MemUsage}} {{.CPUPerc}}"], capture_output=True, text=True).stdout
    RESULT["other_containers"] = [l for l in others.splitlines() if not l.startswith("rs-")]
    log("other containers running:", len(RESULT["other_containers"]))
    steps = {"selftest": selftest, "a": opt_a, "b": opt_b, "d": opt_d, "fail": opt_fail}
    for s in (sys.argv[2:] if resume else ["selftest", "a", "d", "fail", "b"] if cmd == "all" else [cmd]):
        steps[s]()
        with open(os.path.join(HERE, "results", f"{tag}.json"), "w") as f:
            json.dump(RESULT, f, indent=1, default=str)
    log("\ndone")


if __name__ == "__main__":
    main()
