#!/usr/bin/env bash
# 01-up.sh — bench stack up: generated secrets, OpenBao Transit key + wrapped data key,
# ClickHouse with the codec key and the executable UDFs, the SQL UDFs, and a round-trip check.
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

if [ ! -f "$ENV_FILE" ]; then
  umask 077
  cat > "$ENV_FILE" <<EOF
BAO_ROOT_TOKEN=$(openssl rand -hex 16)
CH_PASSWORD=$(openssl rand -hex 16)
CH_CODEC_KEY_HEX=$(openssl rand -hex 32)
SQL_UDF_KEY_HEX=$(openssl rand -hex 32)
EOF
  echo "wrote $ENV_FILE"
fi
load_lab_env
mkdir -p "$SECRETS_DIR" "$RESULTS_DIR"

say "OpenBao (dev mode, in memory)"
dc up -d openbao
for _ in $(seq 1 30); do curl -fsS "$BAO_URL/v1/sys/health" >/dev/null 2>&1 && break; sleep 1; done
bao POST sys/mounts/transit '{"type":"transit"}' >/dev/null || true
bao POST transit/keys/prompt '{"type":"aes256-gcm96"}' >/dev/null || true
# The data key for envelope mode: generated by OpenBao, stored only in wrapped form.
bao POST transit/datakey/wrapped/prompt '{"bits":256}' | jq -r .data.ciphertext > "$SECRETS_DIR/dek.wrapped"
printf '%s' "$BAO_ROOT_TOKEN" > "$SECRETS_DIR/bao-token"
chmod 755 "$SECRETS_DIR"; chmod 644 "$SECRETS_DIR"/*   # read by uid 101 in the container (lab only)

say "ClickHouse (bench image with Python for the executable UDFs)"
dc up -d --build ch
for _ in $(seq 1 60); do
  [ "$(docker inspect -f '{{.State.Health.Status}}' prompt-enc-ch-1 2>/dev/null)" = healthy ] && break; sleep 2
done
ch -q "SELECT version()"

say "SQL UDFs (built-in encrypt/decrypt, AES-256-GCM, nonce = first 12 bytes of SHA-256 of the value)"
K="unhex('$SQL_UDF_KEY_HEX')"
ch --multiquery <<SQL
CREATE FUNCTION IF NOT EXISTS enc_sql AS (x) ->
  if(x = '', '', concat('v1:', base64Encode(concat(substring(SHA256(x), 1, 12),
     encrypt('aes-256-gcm', x, $K, substring(SHA256(x), 1, 12))))));
CREATE FUNCTION IF NOT EXISTS dec_sql AS (c) ->
  if(c = '', '', decrypt('aes-256-gcm', substring(base64Decode(substring(c, 4)), 13), $K,
     substring(base64Decode(substring(c, 4)), 1, 12)));
SQL

say "Round trip of every function"
PASSES=0; FAILS=0
V='[{"role":"user","content":"계좌 110-23-811297 잔액 알려줘\ttab"}]'
for f in sql local kms_batch kms_row kms_batch_rtt5 kms_row_rtt5; do
  got=$(ch --param_v "$V" -q "SELECT dec_${f}(enc_${f}({v:String})) = {v:String}, startsWith(enc_${f}({v:String}), 'v') FORMAT TSV")
  check "dec_${f}(enc_${f}(v)) = v, ciphertext prefix" "$(printf '1\t1')" "$got"
done
got=$(ch -q "SELECT enc_local('') = '' AND dec_local('') = '' AND enc_kms_row('') = ''")
check "empty values stay empty" 1 "$got"
ch -q "DROP TABLE IF EXISTS default.codec_probe"
ch -q "CREATE TABLE default.codec_probe (s String CODEC(ZSTD(3), AES_256_GCM_SIV)) ENGINE = MergeTree ORDER BY tuple()"
ch -q "INSERT INTO default.codec_probe VALUES ('codec-roundtrip')"
check "AES_256_GCM_SIV codec table reads back" codec-roundtrip "$(ch -q 'SELECT s FROM default.codec_probe')"
ch -q "DROP TABLE default.codec_probe"
echo; echo "01-up: $PASSES PASS, $FAILS FAIL"
[ "$FAILS" -eq 0 ]
